// Comprehensive QA Automation Test Suite for Class Companion
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const BASE_URL = "http://localhost:8080";
const SNAPSHOTS_FILE = path.resolve(process.cwd(), ".erp-attendance.json");

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

async function runSuite() {
  console.log("===============================================================");
  console.log("CLASS COMPANION — QA AUTOMATION FUNCTIONALITY AUDIT TEST SUITE");
  console.log("===============================================================\n");

  const results = [];

  // TEST 1: Telegram Bot Connection & Message Delivery from Website
  console.log("[TEST 1] Testing Telegram message delivery generated by website backend...");
  try {
    const res = await fetch(`${BASE_URL}/api/public/test-telegram`);
    const data = await res.json();
    if (res.ok && data.ok && data.messageId) {
      console.log(`  -> SUCCESS: Message delivered! Telegram Message ID: ${data.messageId}`);
      results.push({ test: "TEST 1: Website Message Delivery to Telegram", status: "PASS", detail: `Message ID: ${data.messageId}` });
    } else {
      console.error("  -> FAILED:", data);
      results.push({ test: "TEST 1: Website Message Delivery to Telegram", status: "FAIL", detail: JSON.stringify(data) });
    }
  } catch (err) {
    console.error("  -> ERROR:", err.message);
    results.push({ test: "TEST 1: Website Message Delivery to Telegram", status: "FAIL", detail: err.message });
  }

  // TEST 2: Manual Attendance Poll & Data Retrieval
  console.log("\n[TEST 2] Triggering manual attendance check via /api/public/poll-attendance...");
  try {
    const res = await fetch(`${BASE_URL}/api/public/poll-attendance`);
    const data = await res.json();
    if (res.ok && data.ok && data.parsed > 0) {
      console.log(`  -> SUCCESS: Retrieved ${data.parsed} courses from KL ERP.`);
      results.push({ test: "TEST 2: Manual Attendance Fetching", status: "PASS", detail: `Parsed ${data.parsed} courses` });
    } else {
      console.error("  -> FAILED:", data);
      results.push({ test: "TEST 2: Manual Attendance Fetching", status: "FAIL", detail: JSON.stringify(data) });
    }
  } catch (err) {
    console.error("  -> ERROR:", err.message);
    results.push({ test: "TEST 2: Manual Attendance Fetching", status: "FAIL", detail: err.message });
  }

  // TEST 3: 10-Minute Scheduler Verification
  console.log("\n[TEST 3] Verifying 10-minute automated attendance monitoring configuration...");
  try {
    const pollerScript = readFileSync(path.resolve(process.cwd(), "telegram-poller.mjs"), "utf-8");
    const has10MinInterval = pollerScript.includes("TEN_MINUTES_MS") && pollerScript.includes("setInterval(runAttendancePoll, TEN_MINUTES_MS)");
    const hasSecureEnv = pollerScript.includes("process.env.TELEGRAM_BOT_TOKEN") && !pollerScript.includes('BOT_TOKEN = "861348');
    if (has10MinInterval && hasSecureEnv) {
      console.log("  -> SUCCESS: Background scheduler interval (600,000ms) active with secure env loading.");
      results.push({ test: "TEST 3: 10-Minute Background Scheduler", status: "PASS", detail: "Interval configured & daemon active" });
    } else {
      console.error("  -> FAILED: Scheduler configuration missing or credentials hardcoded.");
      results.push({ test: "TEST 3: 10-Minute Background Scheduler", status: "FAIL", detail: "Configuration incomplete" });
    }
  } catch (err) {
    console.error("  -> ERROR:", err.message);
    results.push({ test: "TEST 3: 10-Minute Background Scheduler", status: "FAIL", detail: err.message });
  }

  // TEST 4: Simulated Attendance Change & Telegram Alert Generation
  console.log("\n[TEST 4] Simulating an attendance change to verify Telegram alert...");
  try {
    const originalContent = readFileSync(SNAPSHOTS_FILE, "utf-8");
    const snapshots = JSON.parse(originalContent);

    // Modify first row to simulate previous attended was lower
    const target = snapshots[0];
    const originalAttended = target.total_attended;
    const originalConducted = target.total_conducted;
    target.total_conducted = Math.max(originalConducted - 1, 0);
    target.total_attended = Math.max(originalAttended - 1, 0);
    writeFileSync(SNAPSHOTS_FILE, JSON.stringify(snapshots, null, 2), "utf-8");

    // Trigger poll
    const res = await fetch(`${BASE_URL}/api/public/poll-attendance`);
    const data = await res.json();

    // Restore snapshots file
    writeFileSync(SNAPSHOTS_FILE, originalContent, "utf-8");

    if (data.ok && Array.isArray(data.changes) && data.changes.length > 0) {
      console.log(`  -> SUCCESS: Detected change: ${data.changes.join(", ")} and sent Telegram alert!`);
      results.push({ test: "TEST 4: Change Detection & Telegram Notification", status: "PASS", detail: `Alert: ${data.changes[0]}` });
    } else {
      console.error("  -> FAILED: No change detected or no alert sent.", data);
      results.push({ test: "TEST 4: Change Detection & Telegram Notification", status: "FAIL", detail: JSON.stringify(data) });
    }
  } catch (err) {
    console.error("  -> ERROR:", err.message);
    results.push({ test: "TEST 4: Change Detection & Telegram Notification", status: "FAIL", detail: err.message });
  }

  // TEST 5: Error Logging & Failed Request Handling
  console.log("\n[TEST 5] Testing error handling on failed/invalid Telegram requests...");
  try {
    const invalidRes = await fetch("https://api.telegram.org/bot8613481579:AAGKXxdS4Y9jkJhFpdOQVDXVefCvI2-shtI/sendMessage", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ chat_id: "00000000", text: "invalid test" }),
    });
    const errJson = await invalidRes.json();
    if (!invalidRes.ok && errJson.ok === false) {
      console.log(`  -> SUCCESS: Error handled properly [HTTP ${invalidRes.status}]: ${errJson.description}`);
      results.push({ test: "TEST 5: Failed Telegram Request Error Handling", status: "PASS", detail: `Caught [HTTP ${invalidRes.status}]` });
    } else {
      results.push({ test: "TEST 5: Failed Telegram Request Error Handling", status: "FAIL", detail: "Unexpected response" });
    }
  } catch (err) {
    results.push({ test: "TEST 5: Failed Telegram Request Error Handling", status: "FAIL", detail: err.message });
  }

  // TEST 6: Duplicate Attendance Notification Prevention
  console.log("\n[TEST 6] Triggering immediate second poll to verify duplicate prevention...");
  try {
    const res = await fetch(`${BASE_URL}/api/public/poll-attendance`);
    const data = await res.json();
    if (data.ok && Array.isArray(data.changes) && data.changes.length === 0) {
      console.log("  -> SUCCESS: 0 duplicate alerts sent! Subsequent poll returned changes: []");
      results.push({ test: "TEST 6: Duplicate Attendance Notification Prevention", status: "PASS", detail: "0 duplicate notifications sent" });
    } else {
      console.error("  -> FAILED: Duplicate changes detected:", data.changes);
      results.push({ test: "TEST 6: Duplicate Attendance Notification Prevention", status: "FAIL", detail: "Duplicates detected" });
    }
  } catch (err) {
    console.error("  -> ERROR:", err.message);
    results.push({ test: "TEST 6: Duplicate Attendance Notification Prevention", status: "FAIL", detail: err.message });
  }

  console.log("\n===============================================================");
  console.log("TEST SUMMARY RESULTS");
  console.log("===============================================================");
  console.table(results);
}

runSuite();

